"""Turn the saved design-test runs into _guides/etl_scenario_results.py for the ETL page.

    python3 _guides/etl_test_publish.py

Reads every _guides/etl_test_runs/run<N>_<date>.json (the reviewer's verdict per check), keeps the
latest run's verdicts and a one-line history of every run, so the page shows real numbers.
"""
import json
import pprint
import re
import sys
from pathlib import Path

HERE = Path(__file__).parent
sys.path.insert(0, str(HERE))
import etl_scenarios as SC  # noqa: E402

runs = sorted(HERE.glob("etl_test_runs/run*_*.json"), key=lambda p: int(re.search(r"run(\d+)_", p.name).group(1)))
history = []
for p in runs:
    d = json.load(open(p))
    r = d["results"]
    by = {x["check"]: x["verdict"] for x in r}
    passing = sum(1 for s in SC.SCENARIOS if all(by.get(f"{s['id']}.{i}") == "STATED" for i in range(1, len(s["then"]) + 1)))
    history.append({"run": int(re.search(r"run(\d+)_", p.name).group(1)), "date": p.stem.split("_", 1)[1],
                    "stated": sum(v == "STATED" for v in by.values()), "gap": sum(v == "GAP" for v in by.values()),
                    "contradicted": sum(v == "CONTRADICTED" for v in by.values()),
                    "feasibility": sum(1 for x in r if x.get("feasibility")),
                    "contradictions_in_page": (len(d["contradictions"]) if "contradictions" in d else None), "passing": passing})
latest = json.load(open(runs[-1]))["results"]
out = HERE / "etl_scenario_results.py"
out.write_text('"""Generated by etl_test_publish.py from etl_test_runs/. Do not edit."""\n\n'
               "RESULTS = " + pprint.pformat({x['check']: {'verdict': x['verdict'], 'note': x.get('note', '')} for x in latest}, width=120) + "\n\n"
               "HISTORY = " + pprint.pformat(history, width=120, sort_dicts=False) + "\n")
for h in history:
    print(h)
